"""Render the downloaded-data manifests into DATA.md tables and refresh config/data_checksums.tsv.

Inputs: config/data_manifest_annotation.tsv, config/data_manifest_orthogonal.tsv, config/data_manifest_extra.tsv
Output: DATA.md section between the markers, config/data_checksums.tsv (user-provided rows kept, downloaded rows appended).
"""
import pathlib, pandas as pd

root = pathlib.Path(__file__).resolve().parents[1]
frames = []
for name in ["annotation", "orthogonal", "extra"]:
    p = root / f"config/data_manifest_{name}.tsv"
    if p.exists():
        d = pd.read_csv(p, sep="\t", dtype=str).fillna("")
        d["group"] = name
        frames.append(d)
m = pd.concat(frames, ignore_index=True)
ok = m[m["sha256"].str.fullmatch(r"[0-9a-f]{64}")]
missing = m[~m.index.isin(ok.index)]

def row(r):
    cells = [r["file"].replace("data/raw/", ""), r["source"], r["url"], r["version"], r["sha256"], r["licence"]]
    return "| " + " | ".join(c.replace("|", "/").replace("\n", " ") for c in cells) + " |"

lines = ["<!-- BEGIN downloaded (generated by scripts/01d_build_data_md_tables.py) -->",
         "| File | Source | URL | Version | SHA-256 | Licence |", "|---|---|---|---|---|---|"]
lines += [row(r) for _, r in ok.iterrows()]
lines += ["", "Not obtained (recorded for transparency):", ""]
lines += [f"- {r['source']}: {r['notes'] or r['version']}" for _, r in missing.iterrows()]
lines += ["<!-- END downloaded -->"]
block = "\n".join(lines)

data_md = (root / "DATA.md").read_text()
if "<!-- BEGIN downloaded" in data_md:
    pre = data_md.split("<!-- BEGIN downloaded")[0]
    post = data_md.split("<!-- END downloaded -->")[1]
    data_md = pre + block + post
else:
    data_md = data_md.rstrip() + "\n\n" + block + "\n"
(root / "DATA.md").write_text(data_md)

ck = root / "config/data_checksums.tsv"
base = [l for l in ck.read_text().splitlines() if l.strip()]
have = {l.split()[1] for l in base}
base += [f"{r['sha256']}  {r['file']}" for _, r in ok.iterrows() if r["file"] not in have]
ck.write_text("\n".join(base) + "\n")
print(f"{len(ok)} downloaded files tabulated, {len(missing)} not obtained; checksums file has {len(base)} rows")
