"""Write placeholder README.md files for data/ (the only files tracked there; all data are git-ignored).

Each data/raw/<source>/README.md lists the files that belong in that folder with their SHA-256 (from
config/data_checksums.tsv), and points to DATA.md for source URL, version and licence. Run from the repository root.
"""
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

PROVIDED = {"depmap", "depmap_rnai", "hgnc", "bioplex", "ccle_proteomics", "ensembl", "humap_train"}
FETCH = {
    "go": "scripts/01a_fetch_annotation_data.sh", "ncbi_gene": "scripts/01a_fetch_annotation_data.sh",
    "uniprot": "scripts/01a_fetch_annotation_data.sh", "unknome": "scripts/01a_fetch_annotation_data.sh",
    "tcrd": "scripts/01a_fetch_annotation_data.sh", "reactome": "scripts/01a_fetch_annotation_data.sh",
    "revision_downloads": "manual download (URLs in results/revision/external_manifest.tsv)",
    "complexportal": "manual download (URL in config/data_manifest_extra.tsv)",
    "mitocarta": "manual download (URL in config/data_manifest_extra.tsv)",
}


def main():
    files = defaultdict(list)
    for line in (ROOT / "config/data_checksums.tsv").read_text().splitlines():
        if not line.strip():
            continue
        sha, path = line.split(maxsplit=1)
        parts = Path(path).parts
        if parts[:2] == ("data", "raw") and len(parts) > 3:
            files[parts[2]].append(("/".join(parts[3:]), sha))
    raw = ROOT / "data/raw"
    sources = sorted(set(files) | {p.name for p in raw.iterdir() if p.is_dir()} if raw.exists() else set(files))
    for src in sources:
        d = raw / src
        d.mkdir(parents=True, exist_ok=True)
        if src in PROVIDED:
            how = ("User-provided files (DepMap portal / HGNC / BioPlex / CCLE / Ensembl / hu.MAP train split); "
                   "download them from the sources listed in DATA.md.")
        else:
            how = f"Fetched by `{FETCH.get(src, 'scripts/01b_fetch_orthogonal_data.sh')}`."
        lines = [f"# data/raw/{src}/ (placeholder — data not distributed)", "",
                 "Everything in this folder except this README is git-ignored. " + how,
                 "Source, version and licence: `DATA.md`. Verify with `scripts/check_data.sh`.", ""]
        if files.get(src):
            lines += ["| file | SHA-256 |", "|---|---|"] + [f"| `{f}` | `{s}` |" for f, s in sorted(files[src])]
        else:
            lines += ["No file from this folder was used in the analyses (download attempted; see DATA.md)."]
        (d / "README.md").write_text("\n".join(lines) + "\n")
    (ROOT / "data/README.md").write_text(
        "# data/ (placeholder — not distributed)\n\n"
        "No data files are included in this repository. `data/raw/<source>/` holds the input datasets (each folder's\n"
        "README lists the expected files and SHA-256 checksums; sources, versions and licences are in `DATA.md`).\n"
        "`data/derived/` and `data/cache/` are regenerated by the numbered scripts (see `README.md`, run order).\n"
        "Everything here except these README files is git-ignored. Never commit DepMap raw files or the\n"
        "CC BY-NC-ND Olivieri 2020 table.\n")
    print(f"{len(sources)} source placeholders written")


if __name__ == "__main__":
    main()
